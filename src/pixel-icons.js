const patterns={
  sunny:['....#....','#...#...#','..#####..','..#####..','#########','..#####..','..#####..','#...#...#','....#....'],
  cloudy:['.........','...###...','..#####..','.#######.','#########','#########','.........','.........','.........'],
  drizzle:['...###...','..#####..','.#######.','#########','#########','.........','..#...#..','.#...#...','.........'],
  storm:['...###...','..#####..','.#######.','#########','#########','.........','.#..#..#.','#..#..#..','..#..#...'],
  auto:['..#####..','.##...##.','##.....##','#.....###','#....####','####....#','###.....#','.##...##.','..#####..'],
};
export function pixelIcon(name){
 const rows=patterns[name]??patterns.cloudy;
 return `<svg viewBox="0 0 11 11" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">${rows.flatMap((row,y)=>[...row].flatMap((v,x)=>v==='#'?[`<rect x="${x+1}" y="${y+1}" width="1" height="1"/>`]:[])).join('')}</svg>`;
}
